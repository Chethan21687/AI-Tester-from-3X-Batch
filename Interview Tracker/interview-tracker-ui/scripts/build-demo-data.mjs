// Generates the anonymized demo dataset (src/data/demoCandidates.js) from the
// real seed (src/data/sampleCandidates.js).
//
// Every pipeline-shaped field (client, req, status, CTC, dates, experience,
// notes) is kept verbatim so the demo dashboard looks like the real one. Every
// identity field (candidate name, email, phone, recruiter/owner) is replaced
// with a deterministic fake, so the demo contains no personal data.
//
// Run: node scripts/build-demo-data.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { sampleCandidates } from '../src/data/sampleCandidates.js'

const __dirname = dirname(fileURLToPath(import.meta.url))

const FIRST = ['Aarav', 'Priya', 'Rohan', 'Meera', 'Vikram', 'Ananya', 'Karan', 'Divya', 'Arjun', 'Neha',
  'Siddharth', 'Kavya', 'Nikhil', 'Sneha', 'Rahul', 'Ishita', 'Aditya', 'Pooja', 'Varun', 'Riya',
  'Manish', 'Shreya', 'Gautam', 'Tanvi', 'Harsh', 'Aditi', 'Sanjay', 'Nisha', 'Yash', 'Lakshmi',
  'Devan', 'Ritika', 'Suraj', 'Preeti', 'Anand', 'Swati', 'Kiran', 'Anjali', 'Vivek', 'Deepa',
  'Mohit', 'Radha', 'Naveen', 'Sunita', 'Pranav', 'Trisha']
const LAST = ['Sharma', 'Iyer', 'Nair', 'Rao', 'Patel', 'Reddy', 'Gupta', 'Menon', 'Joshi', 'Desai',
  'Kulkarni', 'Bhat', 'Chauhan', 'Pillai', 'Verma', 'Shetty', 'Mehta', 'Sinha', 'Kapoor', 'Bose',
  'Naidu', 'Malhotra', 'Dubey', 'Chandra']

// Fixed roster so recruiter breakdowns stay stable across the dashboard.
const RECRUITERS = ['Asha Nair', 'Rajiv Menon', 'Sonal Kapoor', 'Farhan Qureshi']

const pad = (n, w) => String(n).padStart(w, '0')

function identity(i) {
  const first = FIRST[i % FIRST.length]
  const last = LAST[(i * 7) % LAST.length]
  const name = `${first} ${last}`
  const email = `${first}.${last}${pad(i + 1, 3)}@example.com`.toLowerCase()
  // 9xxxxxxxxx, deterministic, clearly synthetic.
  const phone = '9' + pad((100000000 + i * 3571891) % 1000000000, 9)
  return { name, email, phone }
}

// Map each distinct real recruiter to one fixed fake recruiter.
const recruiterMap = new Map()
const mapRecruiter = real => {
  if (!real) return ''
  if (!recruiterMap.has(real)) recruiterMap.set(real, RECRUITERS[recruiterMap.size % RECRUITERS.length])
  return recruiterMap.get(real)
}

const demo = sampleCandidates.map((c, i) => ({
  ...c,
  ...identity(i),
  recruiter: mapRecruiter(c.recruiter),
  owner: c.owner ? mapRecruiter(c.owner) : ''
}))

const js = `// AUTO-GENERATED by scripts/build-demo-data.mjs — DO NOT EDIT BY HAND.
// Anonymized copy of the seed log used by demo mode (?demo=1). Pipeline data is
// real-shaped; all names, emails, phones and recruiters are synthetic.
export const demoCandidates = ${JSON.stringify(demo, null, 2)}
`
writeFileSync(resolve(__dirname, '../src/data/demoCandidates.js'), js)
console.log(`Generated ${demo.length} anonymized demo candidates -> src/data/demoCandidates.js`)
